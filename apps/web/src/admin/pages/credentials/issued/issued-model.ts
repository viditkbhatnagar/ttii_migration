import type { Tone } from '../../../shared/components/ui-kit.js';
import { fmtDate } from '../credential-format.js';
import type { IssuedRow, IssuedStatus } from '../credential-issue-types.js';

export type IssuedTab = 'all' | IssuedStatus;
export const ISSUED_TABS: Array<{ id: IssuedTab; label: string }> = [
  { id: 'all', label: 'All' }, { id: 'valid', label: 'Valid' }, { id: 'superseded', label: 'Superseded' }, { id: 'revoked', label: 'Revoked' },
];
export const STATUS_LABEL: Record<IssuedStatus, string> = { valid: 'Valid', superseded: 'Superseded', revoked: 'Revoked' };
export const STATUS_TONE: Record<IssuedStatus, Tone> = { valid: 'emerald', superseded: 'slate', revoked: 'rose' };

export interface IssuedFilters {
  query: string; course: string; batch: string; centre: string; docType: string; from: string; to: string;
}
export const EMPTY_ISSUED_FILTERS: IssuedFilters = { query: '', course: '', batch: '', centre: '', docType: '', from: '', to: '' };

/** Rows that pass the filters; tab = '' ignores the status (used for the chip counts). */
export function filterIssued(rows: IssuedRow[], tab: IssuedTab, f: IssuedFilters): IssuedRow[] {
  const q = f.query.trim().toLowerCase();
  return rows.filter((r) => {
    if (tab !== 'all' && r.status !== tab) return false;
    if (q && !`${r.learner} ${r.enrolmentNo} ${r.documentNo} ${r.verificationId}`.toLowerCase().includes(q)) return false;
    if (f.course && r.course !== f.course) return false;
    if (f.batch && r.batch !== f.batch) return false;
    if (f.centre && r.centre !== f.centre) return false;
    if (f.docType && r.docType !== f.docType) return false;
    if (f.from && (!r.issueDate || r.issueDate < f.from)) return false;
    if (f.to && (!r.issueDate || r.issueDate > f.to)) return false;
    return true;
  });
}

/** The 16 spec keys, with human headers. Written as CSV: no spreadsheet library is installed. */
export function issuedExportRows(rows: IssuedRow[]): Array<Array<string | number>> {
  const head = [
    'Document no.', 'Verification ID', 'Document type', 'Version', 'Learner', 'Enrolment no.', 'Course', 'Batch', 'Centre',
    'Issue date', 'Generated by', 'Issued by', 'Status', 'Delivery status', 'Scan count', 'Last scanned',
  ];
  const body = rows.map((r) => [
    r.documentNo, r.verificationId, r.docTypeLabel, r.version, r.learner, r.enrolmentNo, r.course, r.batch, r.centre,
    fmtDate(r.issueDate), r.issuedBy, r.issuedBy, STATUS_LABEL[r.status], r.deliveryStatus, r.scanCount, fmtDate(r.lastScanned),
  ]);
  return [head, ...body];
}

/** The public verification page of a row (the detail view uses the server's publicUrl instead). */
export const publicUrlOf = (verificationId: string): string => `https://learn.teachersindia.in/v/${encodeURIComponent(verificationId)}`;
